import { build } from 'esbuild';
import { mkdir, writeFile, rm } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const directory = resolve('.npm-cache/component-audit');
await mkdir(directory, { recursive: true });
const entry = resolve(directory, 'entry.mjs');
await writeFile(entry, 'export { examples } from "../../docs/src/examples.tsx"; export { variants, variantSets } from "../../docs/src/variants.tsx";');
const bundle = resolve(directory, 'catalog.mjs');
await build({ entryPoints: [entry], bundle: true, platform: 'node', format: 'esm', packages: 'external',
  alias: { '@utkristi/ui': resolve('src/react/index.ts') }, outfile: bundle });
const { examples, variants, variantSets } = await import(pathToFileURL(bundle));
const rows = Object.entries(examples).sort(([,a],[,b]) => a.name.localeCompare(b.name)).map(([slug, example]) => {
  const keys = variantSets[slug] ?? [];
  if (!keys.length) throw new Error(slug + ' has no usage variants');
  for (const key of [slug, ...keys]) {
    const entry = key === slug ? example : variants[key];
    if (!entry?.html.trim() || typeof entry.preview !== 'function' || !entry.description.trim()) throw new Error(key + ' has incomplete docs');
  }
  return { slug, name: example.name, variants: keys.map(key => ({ slug: key, name: variants[key].name })) };
});
const variantsCount = rows.reduce((total, row) => total + row.variants.length, 0);
await writeFile('docs/public/component-coverage.json', JSON.stringify({ components: rows.length, variants: variantsCount, entries: rows }, null, 2) + '\n');
const intro = '# Component example coverage\n\nGenerated by npm run docs:audit. This checks that every catalog page has a default example, at least one named usage variant, React preview functions, HTML source, and descriptions. The production docs build separately type-checks all extracted React examples. This is an inventory, not a claim of full competitor feature parity or identical React and native HTML behavior.\n\n';
await writeFile('docs/component-coverage.md', intro + rows.length + ' component pages · ' + variantsCount + ' named variants.\n\n| Component | Usage examples beyond the default |\n| --- | --- |\n' + rows.map(row => '| [' + row.name + '](https://utkristi-ui.vercel.app/#/components/' + row.slug + ') | ' + row.variants.map(v => v.name).join(' · ') + ' |').join('\n') + '\n');
console.log('Verified ' + rows.length + ' components and ' + variantsCount + ' usage variants.');
await rm(entry); await rm(bundle);
